const icons = ["✚", " रक्त", "▣", "₹", "🎁", "●", "✋", "↗"];

const languageSelect = document.querySelector("#language");
const serviceGrid = document.querySelector("#serviceGrid");
const reviewList = document.querySelector("#reviewList");

function setLanguage(lang) {
  const dict = content[lang] || content.en;
  document.documentElement.lang = lang;
  document.body.classList.toggle("lang-mr", lang === "mr");
  document.body.classList.toggle("lang-hi", lang === "hi");

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.dataset.i18n;
    if (dict[key]) node.textContent = dict[key];
  });

  serviceGrid.innerHTML = dict.services
    .map(
      ([title, text], index) => `
        <article class="service-card">
          <div class="service-icon" aria-hidden="true">${icons[index]}</div>
          <h3>${title}</h3>
          <p>${text}</p>
        </article>
      `
    )
    .join("");

  reviewList.innerHTML = dict.review
    .map(
      ([title, text], index) => `
        <article class="review-item">
          <span>${index + 1}</span>
          <div>
            <strong>${title}</strong>
            <p>${text}</p>
          </div>
        </article>
      `
    )
    .join("");

  localStorage.setItem("foundation-language", lang);
}

languageSelect.addEventListener("change", (event) => setLanguage(event.target.value));

const savedLanguage = localStorage.getItem("foundation-language") || "en";
languageSelect.value = savedLanguage;
setLanguage(savedLanguage);

